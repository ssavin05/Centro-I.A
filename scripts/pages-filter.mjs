import {readdir,readFile,writeFile,access} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {resolve,join} from 'node:path';
import {pagesFiles} from './pages-files.mjs';
const root=fileURLToPath(new URL('../',import.meta.url));
export async function filterConfig(folder=root,publicFiles=pagesFiles){
 const allowed=new Set(publicFiles),excluded=new Set(['.git','node_modules','dist','build','.temp','.nojekyll','render.yaml']);
 async function walk(directory,prefix=''){
  for(const item of await readdir(directory,{withFileTypes:true})){
   const name=prefix?prefix+'/'+item.name:item.name;
   if(item.isDirectory()){
    if(publicFiles.some(file=>file.startsWith(name+'/')))await walk(join(directory,item.name),name);
    else excluded.add(name);
   }else if(item.isFile()&&!allowed.has(name))excluded.add(name);
   else if(item.isSymbolicLink())throw Error('No se admiten enlaces en la fuente de publicación: '+name);
  }
 }
 await walk(folder);
 excluded.add('_config.yml');
 return '# Generated by node scripts/pages-filter.mjs --write. Public files come from pages-files.mjs.\nexclude: '+JSON.stringify([...excluded].sort())+'\n';
}
export async function checkFilter(){
 try{await access(join(root,'.nojekyll'));throw Error('La raíz no debe tener .nojekyll: Pages necesita aplicar el filtro. El build de dist crea el suyo.');}catch(error){if(error.code!=='ENOENT')throw error;}
 const expected=await filterConfig(),actual=await readFile(join(root,'_config.yml'),'utf8');
 if(actual!==expected)throw Error('Actualiza el filtro de Pages: node scripts/pages-filter.mjs --write');
 console.log('Pages: fuente de rama filtrada al manifiesto público.');
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 if(process.argv[2]==='--write')await writeFile(join(root,'_config.yml'),await filterConfig());else await checkFilter();
}
