import {mkdirSync,copyFileSync,cpSync,rmSync,writeFileSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=resolve(fileURLToPath(new URL('../',import.meta.url))),dist=join(root,'dist');
rmSync(dist,{recursive:true,force:true});mkdirSync(dist,{recursive:true});
for(const file of ['index.html','auth.html','workspace.html','site.css','start.js','auth.js','workspace.js','manifest.webmanifest'])copyFileSync(join(root,file),join(dist,file));
mkdirSync(join(dist,'assets'),{recursive:true});
cpSync(join(root,'assets/icons'),join(dist,'assets/icons'),{recursive:true});
writeFileSync(join(dist,'.nojekyll'),'');
console.log('Centro I.A. oficial preparado para GitHub Pages. La autenticación requiere backend alojado.');