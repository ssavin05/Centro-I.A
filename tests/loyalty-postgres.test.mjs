import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from 'pglite17';
import {readFile} from 'node:fs/promises';
const ids={owner:'00000000-0000-4000-8000-000000000001',other:'00000000-0000-4000-8000-000000000002',user:'00000000-0000-4000-8000-000000000003',second:'00000000-0000-4000-8000-000000000004'};
async function setup(t){
 const db=await PGlite.create();t.after(()=>db.close());
 await db.exec(`create role anon nologin;create role authenticated nologin;create schema auth;
 create table auth.users(id uuid primary key,raw_user_meta_data jsonb not null default '{}');
 create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
 grant usage on schema auth to anon,authenticated;grant execute on function auth.uid() to anon,authenticated;`);
 await db.exec(await readFile(new URL('../supabase/migrations/20261112_cia_profiles.sql',import.meta.url),'utf8'));
 await db.exec(await readFile(new URL('../supabase/migrations/20261117013535_loyalty_core.sql',import.meta.url),'utf8'));
 for(const [name,id]of Object.entries(ids))await db.query('insert into auth.users values($1,$2)',[id,{name:'Fixture '+name,account_type:['owner','other'].includes(name)?'company':'user'}]);
 const as=(who,sql,args=[],role='authenticated')=>db.transaction(async tx=>{await tx.exec('set local role '+role);await tx.query("select set_config('request.jwt.claim.sub',$1,true)",[ids[who]||'']);return tx.query(sql,args)});
 const rpc=async(who,name,args=[])=>{const result=await as(who,'select public.'+name+'('+args.map((_,i)=>'$'+(i+1)).join(',')+') as value',args);return result.rows[0].value};
 const club=await rpc('owner','cia_create_club',['Negocio aislado','Cafetería','Ciudad de prueba','Solo fixture',10]);
 const code=(await db.query('select join_code from public.cia_clubs where id=$1',[club])).rows[0].join_code;
 return {db,as,rpc,club,code};
}
test('fidelidad PostgreSQL 17: roles, privacidad, alta y unión sin duplicados',async t=>{
 const {db,as,rpc,club,code}=await setup(t);
 assert.match((await db.query('select version() as v')).rows[0].v,/PostgreSQL 17/);
 await assert.rejects(rpc('user','cia_create_club',['No permitido','Otro','Ciudad','',10]),e=>e.code==='42501');
 await assert.rejects(as('user','select public.cia_loyalty_snapshot()',[],'anon'),e=>e.code==='42501');
 await assert.rejects(rpc('user','cia_join_listed_club',[club]),e=>e.code==='22023');
 assert.equal((await rpc('user','cia_loyalty_snapshot')).explore.length,0);
 await rpc('owner','cia_set_club_listed',[club,true]);
 const explore=(await rpc('user','cia_loyalty_snapshot')).explore;
 await db.query("update auth.users set raw_user_meta_data=raw_user_meta_data||'{\"account_type\":\"company\"}'::jsonb where id=$1",[ids.user]);
 await assert.rejects(rpc('user','cia_create_club',['No permitido','Otro','Ciudad','',10]),e=>e.code==='42501');
 assert.equal(explore[0].name,'Negocio aislado');assert.equal(explore[0].join_code,undefined);assert.equal(explore[0].owner_id,undefined);
 await rpc('user','cia_join_club',[code.toLowerCase()]);await rpc('user','cia_join_club',[code]);
 assert.equal((await db.query('select count(*)::int as n from cia_club_members')).rows[0].n,1);
 assert.equal((await rpc('user','cia_loyalty_snapshot')).clubs[0].join_code,null);
 assert.equal((await as('other','select * from cia_club_members')).rows.length,0);
 await assert.rejects(as('user','update cia_club_members set points=10000'),e=>e.code==='42501');
 await assert.rejects(rpc('other','cia_set_club_listed',[club,false]),e=>e.code==='42501');
});
