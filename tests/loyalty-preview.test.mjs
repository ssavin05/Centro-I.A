import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {createLoyaltyPreview} from '../scripts/loyalty-preview.mjs';
test('prueba local: API aislada, canje concurrente idempotente y persistencia al reiniciar',async t=>{
 const directory=await mkdtemp(join(tmpdir(),'centro-loyalty-'));
 let app=await createLoyaltyPreview({dataDir:directory,port:0});
 t.after(async()=>{await app.close();if(!resolve(directory).startsWith(resolve(tmpdir(),'centro-loyalty-')))throw Error('Ruta de prueba inesperada');await rm(directory,{recursive:true,force:true});});
 const rpc=async(role,name,args={})=>{const response=await fetch('http://127.0.0.1:'+app.port+'/__local/rpc',{method:'POST',headers:{'Content-Type':'application/json','X-Preview-Token':app.token,'X-Preview-Actor':role},body:JSON.stringify({name,args})});return {status:response.status,value:await response.json()};};
 assert.equal((await fetch('http://127.0.0.1:'+app.port+'/__local/profile')).status,403);
 assert.equal((await rpc('user','execute_sql',{query:'drop table cia_profiles'})).status,403);
 const club=(await rpc('company','cia_create_club',{p_name:'Negocio fixture',p_category:'Prueba',p_city:'Ciudad aislada',p_description:'Solo prueba',p_points:10})).value;
 await rpc('company','cia_set_club_listed',{p_club:club,p_listed:true});
 await rpc('user','cia_join_listed_club',{p_club:club});
 const visit=(await rpc('user','cia_visit_action',{p_club:club,p_action:'arrive'})).value;
 assert.equal((await rpc('user','cia_visit_action',{p_club:club,p_action:'confirm',p_visit:visit})).status,400);
 await rpc('company','cia_visit_action',{p_club:club,p_action:'confirm',p_visit:visit});
 const reward=(await rpc('company','cia_save_reward',{p_club:club,p_title:'Premio fixture',p_description:'',p_cost:10,p_stock:1,p_request:'11111111-1111-4111-8111-111111111111'})).value;
 const args={p_reward:reward,p_request:'22222222-2222-4222-8222-222222222222'};
 const [first,second]=await Promise.all([rpc('user','cia_redeem_reward',args),rpc('user','cia_redeem_reward',args)]);
 assert.equal(first.status,200);assert.equal(second.status,200);assert.equal(first.value,second.value);
 await app.close();app=await createLoyaltyPreview({dataDir:directory,port:0});
 const result=(await rpc('user','cia_loyalty_snapshot')).value;
 assert.equal(result.redemptions.length,1);assert.equal(result.clubs[0].points,0);assert.equal(result.rewards[0].stock,0);
 const client=await(await fetch('http://127.0.0.1:'+app.port+'/supabase-client.js')).text();
 assert.doesNotMatch(client,/supabase\.co|publishable_/);
 const page=await(await fetch('http://127.0.0.1:'+app.port+'/workspace.html')).text();
 assert.match(page,/PRUEBA LOCAL/);
});
